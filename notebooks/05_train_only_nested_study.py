# %% [markdown]
# ## Зведена таблиця стратегій
#
# Кожен рядок описує повний алгоритм: внутрішній вибір параметрів → калібрування (за потреби) → навчання базової моделі → прогноз наступного періоду. Класифікаційні метрики обчислюються на всіх зовнішніх спорах, включно зі спорами з невідомою сумою; Score — лише на однакових спорах із сумою, придатною для Score (кількість наведено окремо).
#
# Pooled log loss і Brier обчислюються за об'єднаними зовнішніми прогнозами, а не як незважене середнє зрізів. Pooled ROC-AUC додатково враховує ранжування між періодами; ROC-AUC кожного періоду наведено окремо. Колонки `observed_*` виключають відновлені й виправлені суми; підмножини основного й observed-сценаріїв різні, у межах сценарію — однакові для всіх моделей. Невідомі суми не замінюються нулями.

