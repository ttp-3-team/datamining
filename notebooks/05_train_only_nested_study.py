# ## Обмеження
#
# - Протокол обирає стратегію, але не встановлює статистично значущої переваги. Трьох зовнішніх періодів недостатньо для висновків про стійкість.
# - Ці дані train раніше використовувалися для огляду даних і попереднього порівняння. Вкладена схема усуває локальний підбір параметрів і калібрування, але не попереднє ознайомлення з даними та вибір простору кандидатів.
# - Validation раніше використовувалася для вибору; це дослідження не відновлює її незалежності. Файли validation і test тут не відкривалися.
# - Дата отримання результату спору відсутня, тому не перевірено, чи були навчальні мітки доступні на момент наступного прогнозу. Це обмеження стосується всіх часових перевірок у роботі.
# - Вибірка містить лише спори, за які боролися й отримали результат. Відновлення сум і частка спорів із сумою, придатною для Score, також обмежують узагальнення.
#
# Ноутбук не оцінює validation чи test і не змінює порогу практичної близькості після перегляду результатів.
#
# `protocol.json` містить зафіксоване правило, `selection.json` — вибір і параметри кожного зовнішнього зрізу, `run_evidence.json` — хеші коду й результатів і журнал фактично відкритих CSV. Аудит-хук Python блокує відкриття інших таблиць `outputs/`, а також CSV набору даних, validation, test і `unknown_time`.
