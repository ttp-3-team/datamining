# %% [markdown]
# ## Правило вибору, зафіксоване до отримання результатів
#
# Основний критерій — сумарний Score на спорах із сумою, придатною для Score. Практично близькими вважаються стратегії, Score яких відстає від найбільшого не більше ніж на 0,05 USD × кількість оцінених спорів. Цей поріг є робочим припущенням щодо достатньої користі від ускладнення, а не статистичним критерієм.
#
# Серед близьких стратегій обирається простіша в порядку: стала ймовірність train → ЛР → калібрована ЛР → бустинг → калібрований бустинг → ансамбль. За однакової складності порівнюються послідовно: найменший за періодами приріст відносно сталої ймовірності на один спір (більший кращий), стандартне відхилення цього приросту (менше краще), pooled log loss (менший кращий), назва стратегії. Складність визначено зафіксованим порядком, а не числовою мірою.
#
# Результат без відновлених і виправлених сум є перевіркою чутливості і не використовується для зміни правила вибору.

# %% [markdown]
# ## Вкладений вибір параметрів і калібрування
#
# Для кожного зовнішнього періоду train два внутрішні зрізи порівнюють `C` = 0,01; 0,1; 1; 10; 100 для ЛР і шість фіксованих конфігурацій бустингу. Обирається найбільший сумарний внутрішній Score; за рівності — менший pooled log loss, потім менше `C` або назва конфігурації. Попередня обробка навчається заново; мітки зовнішнього періоду для вибору параметрів не використовуються.
#
# Для кожної обраної моделі збираються її позачасові прогнози на внутрішніх пізніших підперіодах; на них і відповідних мітках навчається sigmoid-калібратор. Модель, що дала кожен такий прогноз, навчена лише на ранніших тижнях; мітки зовнішнього періоду калібратору недоступні. Внутрішні прогнози використовуються і для вибору параметрів, і для калібрування, тому незалежною оцінкою є лише результат на зовнішньому зрізі.
#
# Калібрування застосовується за наявності щонайменше 1000 прогнозів, 50 прикладів кожного класу і двох внутрішніх періодів. Це евристичний критерій обсягу, а не гарантія якості калібрування. За недостатнього обсягу використовуються некалібровані прогнози, випадок позначається, а калібрований варіант виключається з вибору.
#
# Ансамбль — середнє некаліброваних налаштованих ЛР і бустингу з рівними вагами. Після збору прогнозів для калібрування базові моделі перенавчаються на всьому зовнішньому train; відповідність калібратора цим моделям оцінюється на зовнішньому зрізі.
#
# Окрема сітка `C` на всіх трьох зовнішніх періодах є діагностикою чутливості і не замінює вкладеного вибору, у якому `C` визначається лише за минулими даними. Скрізь застосовується правило рішення p × 0,2 × amount_usd > 6.

